/** A registration UID is assigned by the account service, never generated by this client. */
export function normalizeRegistrationUid(value) {
  if (Number.isSafeInteger(value) && value > 0) return String(value);
  return typeof value === "string" && /^[1-9]\d{0,19}$/.test(value) ? value : "";
}

/** Rejection sampling keeps all five rewards equally likely without modulo bias. */
export function drawCheckinReward(cryptoSource = globalThis.crypto) {
  if (!cryptoSource?.getRandomValues) throw new Error("无法生成签到奖励，请使用支持 Web Crypto 的浏览器。");
  const range = CHECKIN_REWARD_MAX - CHECKIN_REWARD_MIN + 1;
  const limit = Math.floor(0x100000000 / range) * range;
  const bytes = new Uint32Array(1);
  let value;
  do { cryptoSource.getRandomValues(bytes); value = bytes[0]; } while (value >= limit);
  return CHECKIN_REWARD_MIN + value % range;
}

export function createUuid(cryptoSource = globalThis.crypto) {
  if (cryptoSource?.randomUUID) return cryptoSource.randomUUID();
  const bytes = new Uint8Array(16);
  if (!cryptoSource?.getRandomValues) throw new Error("无法安全生成身份标识，请换用支持 Web Crypto 的浏览器。");
  cryptoSource.getRandomValues(bytes);
  bytes[6] = (bytes[6] & 15) | 64;
  bytes[8] = (bytes[8] & 63) | 128;
  const hex = [...bytes].map(x => x.toString(16).padStart(2, "0")).join("");
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
}

export function ensureProfileUuid(profile = {}, uuidFactory = createUuid) {
  return { ...profile, uid: normalizeRegistrationUid(profile.uid), uuid: validActor(profile.uuid) ? profile.uuid.toLowerCase() : uuidFactory() };
}

/** UTC+08 has no DST; shifts are used only for date partitioning, never for timestamps. */
export function chinaDay(value = new Date()) {
  const time = new Date(value).getTime();
  if (!Number.isFinite(time)) throw new Error("日期无效");
  return new Date(time + 8 * 3600000).toISOString().slice(0, 10);
}
export function addDays(day, count) {
  return new Date(Date.parse(`${day}T00:00:00Z`) + count * 86400000).toISOString().slice(0, 10);
}
export function isCalendarDay(value) {
  return typeof value === "string" && /^\d{4}-\d{2}-\d{2}$/.test(value) && Number(value.slice(0, 4)) >= 1970 && Number(value.slice(0, 4)) <= 9998 && validDate(`${value}T00:00:00Z`) && new Date(`${value}T00:00:00Z`).toISOString().slice(0, 10) === value;
}
export function shiftCalendarDay(day, view, offset) {
  if (!isCalendarDay(day)) return "";
  if (view === "week") return addDays(day, offset * 7);
  const date = new Date(`${day.slice(0, 7)}-01T00:00:00Z`);
  date.setUTCMonth(date.getUTCMonth() + offset);
  return date.toISOString().slice(0, 10);
}

/** Real Monday-first week/month calendar. Adjacent-month days are present but explicitly marked. */
export function checkinCalendar(state, actorId, { view = "month", day, now = new Date() } = {}) {
  const today = chinaDay(now), anchor = isCalendarDay(day) ? day : today;
  const first = view === "week" ? anchor : `${anchor.slice(0, 7)}-01`;
  const offset = (new Date(`${first}T00:00:00Z`).getUTCDay() + 6) % 7;
  const start = addDays(first, -offset);
  const monthEnd = shiftCalendarDay(first, "month", 1);
  const length = view === "week" ? 7 : Math.ceil((Date.parse(`${monthEnd}T00:00:00Z`) - Date.parse(`${start}T00:00:00Z`)) / 86400000 / 7) * 7;
  const byDay = new Map(state.checkins.filter(row => row.actorId === actorId).map(row => [row.day, row]));
  const ledger = new Map(state.ledger.filter(row => row.actorId === actorId && row.kind === "checkin").map(row => [row.ref, row]));
  const days = Array.from({ length }, (_, index) => {
    const value = addDays(start, index), record = byDay.get(value), earned = ledger.get(value);
    return { day: value, date: Number(value.slice(8)), checked: Boolean(record), today: value === today, future: value > today, inMonth: value.slice(0, 7) === anchor.slice(0, 7), amount: earned?.amount ?? record?.amount ?? null, dailyReward: record?.dailyReward ?? null, streakBonus: record?.streakBonus ?? null };
  });
  const targetDays = days.filter(row => view === "week" || row.inMonth);
  return { view, anchor, start, end: addDays(start, length), days, checkedCount: targetDays.filter(row => row.checked).length, totalReward: targetDays.reduce((sum, row) => sum + (row.checked ? row.amount || 0 : 0), 0), label: view === "week" ? `${start} 至 ${addDays(start, 6)}` : `${anchor.slice(0, 4)} 年 ${Number(anchor.slice(5, 7))} 月`, isCurrent: view === "week" ? today >= start && today < addDays(start, 7) : today.slice(0, 7) === anchor.slice(0, 7) };
}
export function periodBounds(period = "all", now = new Date()) {
  const today = chinaDay(now);
  if (period === "day") return { start: today, end: addDays(today, 1), label: today };
  if (period === "week") {
    const weekday = new Date(`${today}T00:00:00Z`).getUTCDay();
    const start = addDays(today, -((weekday + 6) % 7));
    return { start, end: addDays(start, 7), label: `${start} 至 ${addDays(start, 6)}` };
  }
  if (period === "month") {
    const start = `${today.slice(0, 7)}-01`;
    const date = new Date(`${start}T00:00:00Z`);
    date.setUTCMonth(date.getUTCMonth() + 1);
    return { start, end: date.toISOString().slice(0, 10), label: today.slice(0, 7) };
  }
  return { start: "", end: "9999-12-31", label: "全部记录" };
}
