export function emptySocialState() {
  return { version: 1, checkins: [], ledger: [], purchases: [], equipped: {}, likes: [], likeFirsts: [], comments: [] };
}

export function normalizeSocialState(value) {
  const empty = emptySocialState();
  if (!value || value.version !== 1) return empty;
  const seen = new Set();
  const checkins = (Array.isArray(value.checkins) ? value.checkins : []).filter(row => {
    if (!validActor(row?.actorId) || !validDate(row.at)) return false;
    const key = `${row.actorId}:${chinaDay(row.at)}`;
    if (seen.has(key)) return false;
    seen.add(key); return true;
  }).map(row => ({ id: `checkin:${row.actorId}:${chinaDay(row.at)}`, actorId: row.actorId, at: asIso(row.at), day: chinaDay(row.at), ...(Number.isInteger(row.dailyReward) && row.dailyReward >= CHECKIN_REWARD_MIN && row.dailyReward <= CHECKIN_REWARD_MAX && [0, STREAK_REWARD].includes(row.streakBonus) ? { dailyReward: row.dailyReward, streakBonus: row.streakBonus, amount: row.dailyReward + row.streakBonus } : {}) })).sort((a, b) => a.at.localeCompare(b.at));
  const ledgerIds = new Set();
  const ledger = (Array.isArray(value.ledger) ? value.ledger : []).filter(row => {
    if (!safeId(row?.id) || ledgerIds.has(row.id) || !validActor(row.actorId) || !Number.isInteger(row.amount) || row.amount === 0 || !validDate(row.at) || !["checkin", "redeem"].includes(row.kind)) return false;
    ledgerIds.add(row.id); return true;
  }).map(row => ({ id: safeId(row.id), actorId: row.actorId, kind: row.kind, amount: row.amount, at: asIso(row.at), ref: safeId(row.ref), label: trim(row.label, 120) }));
  const purchaseIds = new Set();
  const purchases = (Array.isArray(value.purchases) ? value.purchases : []).filter(row => {
    const key = `${row?.actorId}:${row?.itemId}`;
    if (!validActor(row?.actorId) || !HONOR_ITEMS.some(item => item.id === row.itemId) || !validDate(row.at) || purchaseIds.has(key)) return false;
    purchaseIds.add(key); return true;
  }).map(row => ({ actorId: row.actorId, itemId: row.itemId, at: asIso(row.at) }));
  const normalizeLike = row => ({ id: `${row.actorId}:${row.targetType}:${safeId(row.targetId)}`, actorId: row.actorId, actorName: trim(row.actorName, 24), actorAvatar: trim(row.actorAvatar, 40), authorId: validActor(row.authorId) ? row.authorId : "", targetType: row.targetType, targetId: safeId(row.targetId), targetTitle: trim(row.targetTitle, 150), href: safeHref(row.href), at: asIso(row.at) });
  const likeValid = row => validActor(row?.actorId) && ["guide", "comment"].includes(row.targetType) && safeId(row.targetId) && validDate(row.at) && row.actorId !== row.authorId;
  const dedupeLikes = rows => {
    const ids = new Set();
    return (Array.isArray(rows) ? rows : []).filter(likeValid).map(normalizeLike).filter(row => { if (ids.has(row.id)) return false; ids.add(row.id); return true; });
  };
  const likes = dedupeLikes(value.likes);
  const likeFirsts = dedupeLikes([...(Array.isArray(value.likeFirsts) ? value.likeFirsts : []), ...likes]);
  const commentIds = new Set();
  const comments = (Array.isArray(value.comments) ? value.comments : []).filter(row => {
    if (!safeId(row?.id) || commentIds.has(row.id) || !safeId(row.targetId) || !validActor(row.authorId) || !trim(row.body, 2000).trim() || !validDate(row.at)) return false;
    commentIds.add(row.id); return true;
  }).map(row => ({ id: safeId(row.id), targetId: safeId(row.targetId), targetTitle: trim(row.targetTitle, 150), href: safeHref(row.href), authorId: row.authorId, author: trim(row.author, 24) || "未设置昵称", avatar: trim(row.avatar, 40) || "dimo", body: trim(row.body, 2000), at: asIso(row.at) }));
  const equipped = {};
  if (value.equipped && typeof value.equipped === "object") {
    Object.entries(value.equipped).forEach(([actorId, picks]) => {
      if (!validActor(actorId)) return;
      const owned = new Set(purchases.filter(row => row.actorId === actorId).map(row => row.itemId));
      equipped[actorId] = {
        badge: typeof picks?.badge === "string" && (owned.has(picks.badge) || ACHIEVEMENTS.some(a => a.id === picks.badge)) ? picks.badge : "",
        frame: typeof picks?.frame === "string" && owned.has(picks.frame) && HONOR_ITEMS.some(a => a.id === picks.frame && a.kind === "frame") ? picks.frame : "",
      };
    });
  }
  return { ...empty, checkins, ledger, purchases, equipped, likes, likeFirsts, comments };
}

export function checkinSummary(state, actorId, now = new Date()) {
  const today = chinaDay(now);
  const days = [...new Set(state.checkins.filter(row => row.actorId === actorId && row.day <= today).map(row => row.day))].sort();
  let run = 0, longest = 0, previous = "";
  const milestones = days.map(day => {
    run = previous && addDays(previous, 1) === day ? run + 1 : 1;
    previous = day; longest = Math.max(longest, run);
    return { day, streak: run };
  });
  const lastDay = days.at(-1) || "";
  return { total: days.length, current: [today, addDays(today, -1)].includes(lastDay) ? run : 0, longest, lastDay, today, checkedToday: lastDay === today, milestones };
}

export function getSubmissionAuthorIdentity(submission) {
  if (!submission || submission.isExample || !validActor(submission.authorId)) return null;
  return { uuid: submission.authorId, nickname: trim(submission.author, 24) || "未设置昵称", avatar: trim(submission.authorAvatar, 40) || "dimo" };
}
export function contributionEntries(submissions = []) {
  const ids = new Set();
  return (Array.isArray(submissions) ? submissions : []).filter(row => {
    if (!row || row.status !== "published" || row.isExample || !row.id || ids.has(row.id) || !getSubmissionAuthorIdentity(row) || typeof row.before !== "string" || typeof row.after !== "string" || row.before.trim() === row.after.trim()) return false;
    ids.add(row.id); return true;
  }).map(row => {
    const events = (Array.isArray(row.events) ? row.events : []).filter(event => event && validDate(event.at) && /发布|上线/.test(event.label || "")).map(event => event.at).sort();
    const at = validDate(row.firstPublishedAt) ? row.firstPublishedAt : validDate(row.publishedAt) ? row.publishedAt : events[0] || row.updatedAt;
    return { id: row.id, actorId: row.authorId, at, day: validDate(at) ? chinaDay(at) : "", target: trim(row.target, 150) };
  }).filter(row => row.day);
}
export function receivedLikes(state, actorId, now = new Date()) {
  const nowTime = new Date(now).getTime();
  const commentOwners = new Map(state.comments.map(row => [row.id, row.authorId]));
  return state.likes.filter(row => row.authorId === actorId && Date.parse(row.at) <= nowTime && row.actorId !== actorId && (row.targetType === "guide" || commentOwners.get(row.targetId) === actorId));
}
export function influenceStats(state, actorId, submissions = [], now = new Date()) {
  const nowTime = new Date(now).getTime();
  const validLikes = receivedLikes(state, actorId, now);
  const contributions = contributionEntries(submissions).filter(row => row.actorId === actorId && Date.parse(row.at) <= nowTime);
  return { guideLikes: validLikes.filter(row => row.targetType === "guide").length, commentLikes: validLikes.filter(row => row.targetType === "comment").length, contributions: contributions.length, comments: state.comments.filter(row => row.authorId === actorId && Date.parse(row.at) <= nowTime).length };
}
export function walletBalance(state, actorId) {
  return state.ledger.filter(row => row.actorId === actorId).reduce((sum, row) => sum + row.amount, 0);
}
export function earnedAchievements(state, actorId, submissions = [], now = new Date()) {
  const count = influenceStats(state, actorId, submissions, now).contributions;
  const longest = checkinSummary(state, actorId, now).longest;
  return ACHIEVEMENTS.filter(item => item.id === "achievement-first" ? count >= 1 : item.id === "achievement-three" ? count >= 3 : longest >= 7);
}

export function applySocialAction(input, action, { identity, now = new Date(), submissions = [], uuidFactory = createUuid, rewardFactory = drawCheckinReward } = {}) {
  const state = normalizeSocialState(input);
  const actorId = identity?.uuid;
  const fail = (code, message) => ({ ok: false, code, message, state });
  const success = (next, message, result) => ({ ok: true, code: "ok", message, state: next, result });
  if (!validActor(actorId)) return fail("identity-required", "身份标识尚未保存，请先打开个人资料重试。");
  const at = asIso(now), today = chinaDay(now);
  if (action.type === "check-in") {
    const summary = checkinSummary(state, actorId, now);
    if (state.checkins.some(row => row.actorId === actorId && row.day > today)) return fail("clock-backwards", "设备日期早于已有签到记录，请核对系统时间。");
    if (summary.checkedToday) return fail("already-checked", "今天已经签到，明天再见。");
    const id = `checkin:${actorId}:${today}`;
    if (state.ledger.some(row => row.id === id)) return fail("already-checked", "今天的签到奖励已经入账。");
    const streak = summary.lastDay === addDays(today, -1) ? summary.current + 1 : 1;
    let dailyReward;
    try { dailyReward = rewardFactory(); } catch { return fail("reward-unavailable", "暂时无法生成签到奖励，本次没有扣除或增加印记，请稍后重试。"); }
    if (!Number.isInteger(dailyReward) || dailyReward < CHECKIN_REWARD_MIN || dailyReward > CHECKIN_REWARD_MAX) return fail("invalid-reward", "签到奖励生成异常，本次没有记录签到。");
    const streakBonus = streak % 7 === 0 ? STREAK_REWARD : 0;
    const amount = dailyReward + streakBonus;
    const next = { ...state, checkins: [...state.checkins, { id, actorId, at, day: today, dailyReward, streakBonus, amount }], ledger: [...state.ledger, { id, actorId, at, kind: "checkin", amount, ref: today, label: streakBonus ? `每日 ${dailyReward} 枚 · 连续 ${streak} 天额外 +${streakBonus}` : `每日签到 · ${dailyReward} 枚` }] };
    return success(next, `签到成功，获得 ${amount} 枚${CURRENCY_NAME}${streakBonus ? `（每日 ${dailyReward} 枚＋连签 ${streakBonus} 枚）` : ""}。`, { amount, dailyReward, streakBonus, streak });
  }
  if (action.type === "redeem") {
    const item = HONOR_ITEMS.find(row => row.id === action.itemId);
    if (!item) return fail("unknown-item", "这件纪念物暂未收录。");
    if (state.purchases.some(row => row.actorId === actorId && row.itemId === item.id)) return fail("already-owned", "已经拥有，无需重复兑换。");
    if (walletBalance(state, actorId) < item.price) return fail("insufficient-balance", `还差 ${item.price - walletBalance(state, actorId)} 枚${CURRENCY_NAME}。`);
    const next = { ...state, purchases: [...state.purchases, { actorId, itemId: item.id, at }], ledger: [...state.ledger, { id: `redeem:${actorId}:${item.id}`, actorId, at, kind: "redeem", amount: -item.price, ref: item.id, label: `兑换 · ${item.title}` }] };
    return success(next, `已兑换「${item.title}」，可以佩戴到个人名片。`, { item });
  }
  if (action.type === "equip") {
    const slot = action.slot === "frame" ? "frame" : "badge";
    const item = [...HONOR_ITEMS, ...earnedAchievements(state, actorId, submissions, now)].find(row => row.id === action.itemId);
    if (action.itemId && (!item || (slot === "frame" ? item.kind !== "frame" : item.kind === "frame"))) return fail("invalid-slot", "这件纪念物无法放在此位置。");
    const owned = item?.kind === "achievement" || state.purchases.some(row => row.actorId === actorId && row.itemId === action.itemId);
    if (action.itemId && !owned) return fail("not-owned", "先获得这件纪念物，再选择佩戴。");
    return success({ ...state, equipped: { ...state.equipped, [actorId]: { ...(state.equipped[actorId] || { badge: "", frame: "" }), [slot]: action.itemId || "" } } }, action.itemId ? `正在展示「${item.title}」。` : "已取消佩戴。");
  }
  if (action.type === "toggle-like") {
    if (!["guide", "comment"].includes(action.targetType) || !safeId(action.targetId)) return fail("invalid-target", "找不到可以点赞的内容。");
    const comment = action.targetType === "comment" ? state.comments.find(row => row.id === action.targetId) : null;
    if (action.targetType === "comment" && !comment) return fail("missing-comment", "这条评论已不存在。");
    const authorId = comment?.authorId || (validActor(action.authorId) ? action.authorId : "");
    if (authorId === actorId) return fail("self-like", "自己的内容不计入自我点赞。");
    const id = `${actorId}:${action.targetType}:${safeId(action.targetId)}`;
    if (state.likes.some(row => row.id === id)) return success({ ...state, likes: state.likes.filter(row => row.id !== id) }, "已取消点赞。", { active: false });
    const original = state.likeFirsts.find(row => row.id === id);
    const like = original ? { ...original, authorId } : { id, actorId, actorName: trim(identity.nickname, 24), actorAvatar: trim(identity.avatar, 40), authorId, targetType: action.targetType, targetId: safeId(action.targetId), targetTitle: trim(comment?.targetTitle || action.targetTitle, 150), href: safeHref(comment?.href || action.href), at };
    return success({ ...state, likes: [...state.likes, like], likeFirsts: original ? state.likeFirsts : [...state.likeFirsts, like] }, "点赞已保存到本机。", { active: true });
  }
  if (action.type === "add-comment") {
    const body = trim(action.body, 2000).trim();
    if (!safeId(action.targetId) || body.length < 2) return fail("comment-too-short", "评论至少填写 2 个字符。");
    if (typeof action.body === "string" && action.body.length > 2000) return fail("comment-too-long", "评论最多 2000 个字符。");
    const comment = { id: `comment:${uuidFactory()}`, targetId: safeId(action.targetId), targetTitle: trim(action.targetTitle, 150), href: safeHref(action.href), authorId: actorId, author: trim(identity.nickname, 24) || "未设置昵称", avatar: trim(identity.avatar, 40) || "dimo", body, at };
    return success({ ...state, comments: [...state.comments, comment] }, "评论已保存在本机。", { comment });
  }
  if (action.type === "delete-comment") {
    const comment = state.comments.find(row => row.id === action.commentId);
    if (!comment || comment.authorId !== actorId) return fail("not-comment-author", "只能移除自己的评论。");
    return success({ ...state, comments: state.comments.filter(row => row.id !== comment.id), likes: state.likes.filter(row => !(row.targetType === "comment" && row.targetId === comment.id)) }, "已移除自己的评论。");
  }
  return fail("unknown-action", "暂不支持这项操作。");
}

export function rankCommunity({ state, participants, submissions = [], metric = "checkins", period = "all", now = new Date() }) {
  const bounds = periodBounds(period, now), currentTime = new Date(now).getTime();
  const contributions = contributionEntries(submissions);
  const rows = participants.map(person => {
    const summary = checkinSummary(state, person.uuid, now);
    let value = 0;
    if (metric === "checkins") value = summary.milestones.filter(row => inPeriod(row.day, bounds)).length;
    else if (metric === "streak") value = Math.max(0, ...summary.milestones.filter(row => inPeriod(row.day, bounds)).map(row => row.streak));
    else if (metric === "guideLikes") value = state.likes.filter(row => row.authorId === person.uuid && row.targetType === "guide" && Date.parse(row.at) <= currentTime && inPeriod(chinaDay(row.at), bounds)).length;
    else if (metric === "contributions") value = contributions.filter(row => row.actorId === person.uuid && Date.parse(row.at) <= currentTime && inPeriod(row.day, bounds)).length;
    return { ...person, value };
  }).filter(row => row.value > 0).sort((a, b) => b.value - a.value || a.uuid.localeCompare(b.uuid));
  let rank = 0;
  return rows.map((row, index) => { if (index === 0 || row.value !== rows[index - 1].value) rank = index + 1; return { ...row, rank }; });
}

