import {appendFile} from 'node:fs/promises';
const token=process.env.CLOUDFLARE_ZONE_API_TOKEN||process.env.CLOUDFLARE_API_TOKEN;
if(!token)throw Error('Missing Cloudflare zone token');
const requestedZone=process.env.CLOUDFLARE_ZONE_ID;
if(requestedZone&&!/^[a-f0-9]{32}$/.test(requestedZone))throw Error('Invalid Cloudflare zone ID');
const response=await fetch(`https://api.cloudflare.com/client/v4/zones${requestedZone?`/${requestedZone}`:'?name=rocoai.app'}`,{headers:{Authorization:`Bearer ${token}`},signal:AbortSignal.timeout(15000)});
type Zone={id:string;name:string;status:string;account:{id:string}};
const data=await response.json() as {success:boolean;result?:Zone|Zone[];errors?:{code:number}[]};
if(!response.ok||!data.success)throw Error(`Cloudflare zone lookup failed (${response.status}; codes: ${(data.errors??[]).map(error=>error.code).join(',')})`);
const rows=Array.isArray(data.result)?data.result:data.result?[data.result]:[];
const zones=rows.filter(zone=>zone.name==='rocoai.app'&&zone.status==='active');
if(zones.length!==1||!/^[a-f0-9]{32}$/.test(zones[0].account.id))throw Error('Expected one active rocoai.app zone with an account ID');
const id=zones[0].account.id;
if(process.env.CLOUDFLARE_ACCOUNT_ID&&process.env.CLOUDFLARE_ACCOUNT_ID!==id)throw Error('Configured account does not own rocoai.app');
if(!process.env.GITHUB_OUTPUT)throw Error('Missing GITHUB_OUTPUT');
await appendFile(process.env.GITHUB_OUTPUT,`account_id=${id}\nzone_id=${zones[0].id}\n`);
console.log('Cloudflare account verified against the active rocoai.app zone.');
